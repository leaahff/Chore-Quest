export const DynamicIcon: React.FC<{ name: string } & LucideProps> = ({ name, ...props }) => {
  const normalizedKey = name.replace(/[-_]/g, '').toLowerCase();
  const IconComponent =
    ICON_MAP[name] ||
    Object.entries(ICON_MAP).find(([k]) => k.toLowerCase() === normalizedKey)?.[1] ||
    Sparkles;

  return <IconComponent {...props} />;
};
